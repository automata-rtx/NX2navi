"""Assemble native R32UI storage-write probes.

Each invocation writes at (2, 3) plus its global XY coordinate. The two-target
variant adds the first target's sampled texel at (0, 0) to both writes.
"""
from make_dlaa_mask import Asm, string


def assemble(paired):
    asm = Asm()
    main, void, fn, u32, u2, u3, u4 = (asm.id() for _ in range(7))
    image, input_pointer, image_pointer, invocation, destination = (asm.id() for _ in range(5))
    x, y, zero, value, origin, pixel = (asm.id() for _ in range(6))
    label, global_id, xy, coordinate, storage = (asm.id() for _ in range(5))
    if paired:
        second, sample, sampled_image, sampled_pointer, sample_at, one = (asm.id() for _ in range(6))
        read_image, fetched, seed, color, color2, pixel2, storage2 = (asm.id() for _ in range(7))

    asm.op("cap", 17, 1)  # Shader
    asm.op("mem", 14, 0, 1)  # Logical GLSL450
    asm.op("entry", 15, 5, main, *string("main"), invocation)
    asm.op("exec", 16, main, 17, 1, 1, 1)
    asm.op("dec", 71, invocation, 11, 28)  # GlobalInvocationId
    for binding, output in enumerate((destination, second, sample) if paired else (destination,), 1):
        asm.op("dec", 71, output, 34, 0)  # DescriptorSet
        asm.op("dec", 71, output, 33, binding)
    asm.op("types", 19, void)
    asm.op("types", 33, fn, void)
    asm.op("types", 21, u32, 32, 0)
    for vector, count in ((u2, 2), (u3, 3), (u4, 4)):
        asm.op("types", 23, vector, u32, count)
    asm.op("types", 25, image, u32, 1, 0, 0, 0, 2, 33)  # R32ui storage image
    asm.op("types", 32, input_pointer, 1, u3)
    asm.op("types", 32, image_pointer, 0, image)
    if paired:
        asm.op("types", 25, sampled_image, u32, 1, 0, 0, 0, 1, 0)
        asm.op("types", 32, sampled_pointer, 0, sampled_image)
    for token, number in ((x, 2), (y, 3), (zero, 0), (value, 0xe5aa1234)):
        asm.op("types", 43, u32, token, number)
    asm.op("types", 44, u2, origin, x, y)
    if paired:
        asm.op("types", 43, u32, one, 1)
        asm.op("types", 44, u2, sample_at, zero, zero)
    else:
        asm.op("types", 44, u4, pixel, value, zero, zero, zero)
    asm.op("types", 59, input_pointer, invocation, 1)
    asm.op("types", 59, image_pointer, destination, 0)
    if paired:
        asm.op("types", 59, image_pointer, second, 0)
        asm.op("types", 59, sampled_pointer, sample, 0)

    asm.op("func", 54, void, main, 0, fn)
    asm.op("func", 248, label)
    asm.op("func", 61, u3, global_id, invocation)
    asm.op("func", 79, u2, xy, global_id, global_id, 0, 1)  # VectorShuffle
    asm.op("func", 128, u2, coordinate, xy, origin)  # IAdd
    if paired:
        asm.op("func", 61, sampled_image, read_image, sample)
        asm.op("func", 95, u4, fetched, read_image, sample_at, 2, zero)  # ImageFetch with Lod
        asm.op("func", 81, u32, seed, fetched, 0)
        asm.op("func", 128, u32, color, value, seed)
        asm.op("func", 128, u32, color2, color, one)
        asm.op("func", 80, u4, pixel, color, zero, zero, zero)
        asm.op("func", 80, u4, pixel2, color2, zero, zero, zero)
    asm.op("func", 61, image, storage, destination)
    asm.op("func", 99, storage, coordinate, pixel)  # ImageWrite
    if paired:
        asm.op("func", 61, image, storage2, second)
        asm.op("func", 99, storage2, coordinate, pixel2)
    asm.op("func", 253)
    asm.op("func", 56)
    return asm.words()


lines = ["// Generated by tools/make_storage_first_write_probe.py. Do not edit.", "#pragma once", "#include <stdint.h>"]
for name, paired in (("storage_first_write_probe_spv", False), ("storage_write_plan_probe_spv", True)):
    words = assemble(paired)
    lines.append(f"static const uint32_t {name}[] = {{")
    for start in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{word:08x}" for word in words[start:start + 8]) + ",")
    lines.append("};")
HEADER = "\n".join([*lines, ""])
