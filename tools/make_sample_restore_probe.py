"""Build the fragment stage of the ordered sampled-texture restore probe.

Equivalent GLSL fragment code is `color = texture(source, uv)` with location-zero
vec2 input, location-zero vec4 output and binding one of descriptor set zero.
"""
from make_dlaa_mask import Asm, string


a = Asm()
main = a.id()
void, fn, f32, vec2, vec4 = (a.id() for _ in range(5))
image, sampled, input_uv, output_color, uniform_sampler = (a.id() for _ in range(5))
uv, color, source, start, coord, sampler, texel = (a.id() for _ in range(7))

a.op("cap", 17, 1)  # OpCapability Shader
a.op("mem", 14, 0, 1)  # OpMemoryModel Logical GLSL450
a.op("entry", 15, 4, main, *string("main"), uv, color)  # OpEntryPoint Fragment
a.op("exec", 16, main, 7)  # OpExecutionMode OriginUpperLeft
a.op("dec", 71, uv, 30, 0)  # OpDecorate Location
a.op("dec", 71, color, 30, 0)
a.op("dec", 71, source, 34, 0)  # DescriptorSet
a.op("dec", 71, source, 33, 1)  # Binding 0 is the NVN support buffer.
a.op("types", 19, void)
a.op("types", 33, fn, void)
a.op("types", 22, f32, 32)
a.op("types", 23, vec2, f32, 2)
a.op("types", 23, vec4, f32, 4)
a.op("types", 25, image, f32, 1, 0, 0, 0, 1, 0)  # OpTypeImage float 2D sampled
a.op("types", 27, sampled, image)
a.op("types", 32, input_uv, 1, vec2)
a.op("types", 32, output_color, 3, vec4)
a.op("types", 32, uniform_sampler, 0, sampled)
a.op("types", 59, input_uv, uv, 1)
a.op("types", 59, output_color, color, 3)
a.op("types", 59, uniform_sampler, source, 0)
a.op("func", 54, void, main, 0, fn)
a.op("func", 248, start)
a.op("func", 61, vec2, coord, uv)
a.op("func", 61, sampled, sampler, source)
a.op("func", 87, vec4, texel, sampler, coord)  # OpImageSampleImplicitLod
a.op("func", 62, color, texel)
a.op("func", 253)
a.op("func", 56)

words = a.words()
lines = ["// Generated by tools/make_sample_restore_probe.py. Do not edit.",
         "#pragma once", "#include <stdint.h>", "static const uint32_t sample_restore_probe_spv[] = {"]
for index in range(0, len(words), 8):
    lines.append("    " + ", ".join(f"0x{word:08x}" for word in words[index:index + 8]) + ",")
HEADER = "\n".join([*lines, "};", ""])
